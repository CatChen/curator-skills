// Build the static read-only Codex page callback from the shared identity logic.
// No source is generated or evaluated at collector runtime.
import fs from 'node:fs';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {pagePathFingerprint} from './path-fingerprint-source.mjs';
import {sha256} from './portable-sha256.mjs';
import {readSessionSources, observeIdentity} from './identity-probe.mjs';

export function buildCodexIdentity() {
  const sha = sha256.toString();
  return `// Generated by build-codex-identity.mjs. Do not edit directly.\nexport async function codexIdentityPage(input) {\n${String.raw`
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_';
  function b64uEncode(bytes) {
    let out = '';
    for (let i = 0; i < bytes.length; i += 3) {
      const a = bytes[i], b = bytes[i + 1], c = bytes[i + 2];
      out += alphabet[a >> 2] + alphabet[((a & 3) << 4) | ((b ?? 0) >> 4)];
      if (b !== undefined) out += alphabet[((b & 15) << 2) | ((c ?? 0) >> 6)];
      if (c !== undefined) out += alphabet[c & 63];
    }
    return out;
  }
  function b64uDecode(text) {
    if (typeof text !== 'string' || !/^[A-Za-z0-9_-]+$/.test(text) || text.length % 4 === 1) return null;
    let out = [], bits = 0, value = 0;
    for (const c of text) { value = (value << 6) | alphabet.indexOf(c); bits += 6; if (bits >= 8) { bits -= 8; out.push((value >> bits) & 255); value &= (1 << bits) - 1; } }
    return b64uEncode(out) === text ? out : null;
  }
  function canonicalSteamId64(value) {
    return typeof value === 'string' && /^[1-9][0-9]{16}$/.test(value) && value >= '76561197960265728' && value <= '76561202255233023' ? value : null;
  }
  function accountIdMatches(steamid64, accountid) {
    const id = canonicalSteamId64(steamid64);
    if (!id) return false;
    const a = typeof accountid === 'number' && Number.isSafeInteger(accountid) && accountid >= 0 ? accountid :
      typeof accountid === 'string' && /^(?:0|[1-9][0-9]{0,9})$/.test(accountid) ? Number(accountid) : null;
    if (a === null) return false;
    const offset = (Number(id.slice(0,7)) - 7656119) * 10000000000 + Number(id.slice(7)) - 7960265728;
    return offset === a;
  }
  function fingerprintBytes(saltBytes, steamid64) {
    const ascii = str => [...str].map(c => { const n = c.charCodeAt(0); if (n > 127) throw new Error('non-ASCII input'); return n; });
    return [...ascii('curator/steam-account/v1'), 0, ...saltBytes, 0, ...ascii(steamid64)];
  }
`}${sha}\n  async function sha256HexOf(bytes) { return sha256(bytes); }\n${readSessionSources.toString()}\n${observeIdentity.toString()}\n${String.raw`
  const origin = location.origin;
  const result = await observeIdentity({salt: input.salt});
  if (location.origin !== origin) throw new Error('origin changed');
  if (input.candidate === true) {
    result.salt = input.salt;
    if (['https://store.steampowered.com','https://steamcommunity.com'].includes(origin)) result.origin = origin;
  }
  return result;
`}\n}\n`;
}
export function buildPathFingerprint() {
  return '// Generated by build-codex-identity.mjs. Do not edit directly.\nexport ' + pagePathFingerprint.toString().replace('{', '{\n' + sha256.toString()) + '\n';
}
const output = new URL('./codex-identity-page.mjs', import.meta.url);
if (process.argv[1] && pathToFileURL(fs.realpathSync(process.argv[1])).href === import.meta.url) {
  fs.writeFileSync(fileURLToPath(output), buildCodexIdentity());
  fs.writeFileSync(fileURLToPath(new URL('./path-fingerprint.mjs', import.meta.url)), buildPathFingerprint());
}
